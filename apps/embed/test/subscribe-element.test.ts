// @vitest-environment jsdom
import { afterEach, describe, expect, it } from "vitest";

import { defineOteSubscribe, type OteSubscribeElement } from "../src/subscribe-element.js";

defineOteSubscribe();

const ICS_URL = "https://communitybuilders.dev/events/feed.ics";
const RSS_URL = "https://communitybuilders.dev/events/feed.xml";
const JSON_URL = "https://communitybuilders.dev/events/feed.json";

function createElement(attrs: Record<string, string> = {}): OteSubscribeElement {
  const el = document.createElement("ote-subscribe") as OteSubscribeElement;
  for (const [name, value] of Object.entries(attrs)) el.setAttribute(name, value);
  return el;
}

function trigger(el: OteSubscribeElement): HTMLButtonElement {
  return el.shadowRoot!.querySelector<HTMLButtonElement>(".trigger")!;
}

function menuLinks(el: OteSubscribeElement): HTMLAnchorElement[] {
  return Array.from(el.shadowRoot!.querySelectorAll<HTMLAnchorElement>(".menu a"));
}

function badge(el: OteSubscribeElement, group: string): HTMLButtonElement {
  return el.shadowRoot!.querySelector<HTMLButtonElement>(`.trigger[data-group="${group}"]`)!;
}

function menuLinksFor(el: OteSubscribeElement, group: string): HTMLAnchorElement[] {
  const item = badge(el, group).closest(".item")!;
  return Array.from(item.querySelectorAll<HTMLAnchorElement>(".menu a"));
}

function groupLabels(el: OteSubscribeElement): string[] {
  return Array.from(el.shadowRoot!.querySelectorAll(".menu-group-label")).map((node) => node.textContent ?? "");
}

/** The "generated by the OTE converter" disclosures currently rendered (#186). */
function notes(el: OteSubscribeElement): string[] {
  return Array.from(el.shadowRoot!.querySelectorAll(".menu-note")).map((node) => node.textContent ?? "");
}

describe("<ote-subscribe>", () => {
  afterEach(() => {
    document.body.replaceChildren();
  });

  it("disables the trigger when neither feed-ics nor feed-rss is set", () => {
    const el = createElement();
    document.body.append(el);
    expect(trigger(el).disabled).toBe(true);
  });

  it("renders only the Calendar group when only feed-ics is set", () => {
    const el = createElement({ "feed-ics": ICS_URL });
    document.body.append(el);
    trigger(el).click();

    const hrefs = menuLinks(el).map((a) => a.href);
    expect(hrefs).toEqual([
      "https://www.google.com/calendar/render?cid=webcal%3A%2F%2Fcommunitybuilders.dev%2Fevents%2Ffeed.ics",
      "webcal://communitybuilders.dev/events/feed.ics",
      ICS_URL,
    ]);
  });

  it("renders only the RSS group when only feed-rss is set", () => {
    const el = createElement({ "feed-rss": RSS_URL });
    document.body.append(el);
    trigger(el).click();

    const hrefs = menuLinks(el).map((a) => a.href);
    expect(hrefs).toEqual([
      "https://feedly.com/i/subscription/feed/https%3A%2F%2Fcommunitybuilders.dev%2Fevents%2Ffeed.xml",
      "feed://communitybuilders.dev/events/feed.xml",
      RSS_URL,
    ]);
  });

  it("renders all three groups when feed-ics, feed-rss, and feed-json are all set", () => {
    const el = createElement({ "feed-ics": ICS_URL, "feed-rss": RSS_URL, "feed-json": JSON_URL });
    document.body.append(el);
    trigger(el).click();

    expect(el.shadowRoot!.querySelectorAll(".menu-group-label")).toHaveLength(3);
    expect(menuLinks(el)).toHaveLength(9);
  });

  it('renders only the OTE feed group when only feed-json is set and convert="off"', () => {
    const el = createElement({ "feed-json": JSON_URL, convert: "off" });
    document.body.append(el);
    trigger(el).click();

    const hrefs = menuLinks(el).map((a) => a.href);
    expect(hrefs).toEqual([
      "https://reader.opentechevents.org/?subscribe=https%3A%2F%2Fcommunitybuilders.dev%2Fevents%2Ffeed.json",
      "https://tools.opentechevents.org/preview/?feed=https%3A%2F%2Fcommunitybuilders.dev%2Fevents%2Ffeed.json",
      JSON_URL,
    ]);
    expect(groupLabels(el)).toEqual(["OTE feed"]);
    expect(notes(el)).toEqual([]);
  });

  it('"show" filters which links appear, as a full replacement', () => {
    const el = createElement({ "feed-ics": ICS_URL, "feed-rss": RSS_URL, show: "google,feedly" });
    document.body.append(el);
    trigger(el).click();

    expect(menuLinks(el).map((a) => a.textContent)).toEqual([
      "Subscribe with Google Calendar",
      "Subscribe with Feedly",
    ]);
  });

  it('disables the trigger when "show" excludes every link for the provided feed', () => {
    const el = createElement({ "feed-ics": ICS_URL, show: "feedly" });
    document.body.append(el);
    expect(trigger(el).disabled).toBe(true);
  });

  it("toggles aria-expanded and role=menu on open/close", () => {
    const el = createElement({ "feed-ics": ICS_URL });
    document.body.append(el);
    expect(trigger(el).getAttribute("aria-expanded")).toBe("false");
    expect(el.shadowRoot!.querySelector('[role="menu"]')).toBeNull();

    trigger(el).click();
    expect(trigger(el).getAttribute("aria-expanded")).toBe("true");
    expect(el.shadowRoot!.querySelector('[role="menu"]')).not.toBeNull();

    trigger(el).click();
    expect(trigger(el).getAttribute("aria-expanded")).toBe("false");
    expect(el.shadowRoot!.querySelector('[role="menu"]')).toBeNull();
  });

  it("closes on Escape and returns focus to the trigger", () => {
    const el = createElement({ "feed-ics": ICS_URL });
    document.body.append(el);
    trigger(el).click();
    expect(el.shadowRoot!.querySelector('[role="menu"]')).not.toBeNull();

    document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
    expect(el.shadowRoot!.querySelector('[role="menu"]')).toBeNull();
    expect(el.shadowRoot!.activeElement).toBe(trigger(el));
  });

  it("closes on an outside click, without moving focus", () => {
    const el = createElement({ "feed-ics": ICS_URL });
    const outside = document.createElement("button");
    document.body.append(el, outside);
    trigger(el).click();
    expect(el.shadowRoot!.querySelector('[role="menu"]')).not.toBeNull();

    outside.dispatchEvent(new PointerEvent("pointerdown", { bubbles: true, composed: true }));
    expect(el.shadowRoot!.querySelector('[role="menu"]')).toBeNull();
  });

  it("does not close on a click inside the element (e.g. on the menu itself)", () => {
    const el = createElement({ "feed-ics": ICS_URL });
    document.body.append(el);
    trigger(el).click();

    el.shadowRoot!.querySelector(".menu")!.dispatchEvent(new PointerEvent("pointerdown", { bubbles: true, composed: true }));
    expect(el.shadowRoot!.querySelector('[role="menu"]')).not.toBeNull();
  });

  describe('layout="badges"', () => {
    it("renders one badge per available group, and none for groups without a feed URL", () => {
      // convert="off" so that this stays a test of "a group needs a URL":
      // with the conversion fallback on, feed-json alone supplies RSS too
      // (see "the conversion-service fallback" below).
      const el = createElement({ "feed-ics": ICS_URL, "feed-json": JSON_URL, layout: "badges", convert: "off" });
      document.body.append(el);

      const groups = Array.from(el.shadowRoot!.querySelectorAll<HTMLButtonElement>(".trigger")).map(
        (t) => t.dataset.group,
      );
      expect(groups).toEqual(["ics", "ote"]);
    });

    it("each badge opens only its own group's links", () => {
      const el = createElement({ "feed-ics": ICS_URL, "feed-rss": RSS_URL, layout: "badges" });
      document.body.append(el);

      badge(el, "rss").click();
      expect(menuLinksFor(el, "rss").map((a) => a.href)).toEqual([
        "https://feedly.com/i/subscription/feed/https%3A%2F%2Fcommunitybuilders.dev%2Fevents%2Ffeed.xml",
        "feed://communitybuilders.dev/events/feed.xml",
        RSS_URL,
      ]);
      // No group-section label needed in badge popovers — the badge itself identifies the group.
      expect(el.shadowRoot!.querySelector(".menu-group-label")).toBeNull();
    });

    it("opening one badge closes another that was already open (mutually exclusive)", () => {
      const el = createElement({ "feed-ics": ICS_URL, "feed-rss": RSS_URL, layout: "badges" });
      document.body.append(el);

      badge(el, "ics").click();
      expect(badge(el, "ics").getAttribute("aria-expanded")).toBe("true");

      badge(el, "rss").click();
      expect(badge(el, "rss").getAttribute("aria-expanded")).toBe("true");
      expect(badge(el, "ics").getAttribute("aria-expanded")).toBe("false");
    });

    it("closes on Escape and returns focus to the badge that was open", () => {
      const el = createElement({ "feed-ics": ICS_URL, "feed-rss": RSS_URL, layout: "badges" });
      document.body.append(el);

      badge(el, "rss").click();
      document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
      expect(el.shadowRoot!.querySelector('[role="menu"]')).toBeNull();
      expect(el.shadowRoot!.activeElement).toBe(badge(el, "rss"));
    });
  });

  // #186: convert.opentechevents.org generates ICS and RSS from an OTE JSON
  // feed, so a publisher who hosts only feed.json still offers "add to
  // calendar" and a feed-reader link. Every entry in the public adopters
  // registry is JSON-only, which is why this is on by default.
  describe("the conversion-service fallback", () => {
    const CONVERT_ICS = "https://convert.opentechevents.org/ics?feed=https%3A%2F%2Fcommunitybuilders.dev%2Fevents%2Ffeed.json";
    const CONVERT_RSS = "https://convert.opentechevents.org/rss?feed=https%3A%2F%2Fcommunitybuilders.dev%2Fevents%2Ffeed.json";

    it("builds the Calendar and RSS groups from the JSON feed alone", () => {
      const el = createElement({ "feed-json": JSON_URL });
      document.body.append(el);
      trigger(el).click();

      expect(groupLabels(el)).toEqual(["Calendar · generated", "RSS · generated", "OTE feed"]);
      expect(menuLinks(el).map((a) => a.href)).toEqual([
        `https://www.google.com/calendar/render?cid=${encodeURIComponent(CONVERT_ICS.replace("https://", "webcal://"))}`,
        CONVERT_ICS.replace("https://", "webcal://"),
        CONVERT_ICS,
        `https://feedly.com/i/subscription/feed/${encodeURIComponent(CONVERT_RSS)}`,
        CONVERT_RSS.replace("https://", "feed://"),
        CONVERT_RSS,
        "https://reader.opentechevents.org/?subscribe=https%3A%2F%2Fcommunitybuilders.dev%2Fevents%2Ffeed.json",
        "https://tools.opentechevents.org/preview/?feed=https%3A%2F%2Fcommunitybuilders.dev%2Fevents%2Ffeed.json",
        JSON_URL,
      ]);
    });

    it("never replaces a URL the publisher declared", () => {
      const el = createElement({ "feed-ics": ICS_URL, "feed-json": JSON_URL });
      document.body.append(el);
      trigger(el).click();

      const hrefs = menuLinks(el).map((a) => a.href);
      expect(hrefs).toContain(ICS_URL);
      expect(hrefs.filter((href) => href.includes("convert.opentechevents.org/ics"))).toEqual([]);
      // The RSS half is still missing, so that one is generated.
      expect(hrefs).toContain(CONVERT_RSS);
    });

    it("is per-format: convert=\"ics\" leaves RSS absent", () => {
      const el = createElement({ "feed-json": JSON_URL, convert: "ics" });
      document.body.append(el);
      trigger(el).click();

      expect(groupLabels(el)).toEqual(["Calendar · generated", "OTE feed"]);
    });

    it("discloses which groups the converter generated, and only those", () => {
      const el = createElement({ "feed-ics": ICS_URL, "feed-json": JSON_URL });
      document.body.append(el);
      trigger(el).click();

      // One note, under RSS — the generated group — and none under the
      // publisher's own Calendar URL.
      // The publisher's own Calendar group is not tagged; the generated RSS
      // one is. The note itself appears once, at the end — the same
      // sentence under every generated group reads as a glitch, and the
      // common case generates two.
      expect(groupLabels(el)).toEqual(["Calendar", "RSS · generated", "OTE feed"]);
      expect(notes(el)).toEqual(["Generated from the OTE feed by the OTE converter."]);
      const children = Array.from(el.shadowRoot!.querySelector(".popover")!.children).map((node) => node.className);
      expect(children).toEqual(["menu", "menu-note"]);
    });

    it("discloses it in Spanish too", () => {
      const el = createElement({ "feed-json": JSON_URL, lang: "es" });
      document.body.append(el);
      trigger(el).click();

      expect(notes(el)).toEqual(["Generado desde el feed OTE por el conversor de OTE."]);
      expect(groupLabels(el)).toEqual(["Calendario · generado", "RSS · generado", "Feed OTE"]);
    });

    it("marks a generated badge and notes inside its own popover", () => {
      const el = createElement({ "feed-json": JSON_URL, layout: "badges" });
      document.body.append(el);

      expect(badge(el, "ics").dataset.generated).toBe("");
      expect(badge(el, "rss").dataset.generated).toBe("");
      expect(badge(el, "ote").dataset.generated).toBeUndefined();

      badge(el, "ics").click();
      expect(notes(el)).toEqual(["Generated from the OTE feed by the OTE converter."]);
      expect(menuLinksFor(el, "ics").map((a) => a.href)).toContain(CONVERT_ICS);
    });

    it("generates nothing from a feed URL the service could not fetch", () => {
      // A relative feed-json works for the OTE group (the browser resolves
      // it) but the converter resolves the URL itself, so a generated link
      // would be guaranteed to 400. Absent beats broken.
      const el = createElement({ "feed-json": "/events/feed.json" });
      document.body.append(el);
      trigger(el).click();

      expect(groupLabels(el)).toEqual(["OTE feed"]);
      expect(notes(el)).toEqual([]);
    });

    it("stays disabled when there is no feed at all", () => {
      const el = createElement();
      document.body.append(el);
      expect(trigger(el).disabled).toBe(true);
    });

    it("re-renders when convert is toggled at runtime", () => {
      const el = createElement({ "feed-json": JSON_URL });
      document.body.append(el);
      trigger(el).click();
      expect(groupLabels(el)).toEqual(["Calendar · generated", "RSS · generated", "OTE feed"]);

      // The popover stays open across the re-render, so its contents are
      // what changed — no second click, which would close it.
      el.setAttribute("convert", "off");
      expect(groupLabels(el)).toEqual(["OTE feed"]);
      expect(trigger(el).getAttribute("aria-expanded")).toBe("true");
    });

    it("honours show as a full replacement over generated groups too", () => {
      const el = createElement({ "feed-json": JSON_URL, show: "google,json-download" });
      document.body.append(el);
      trigger(el).click();

      expect(menuLinks(el).map((a) => a.textContent)).toEqual([
        "Subscribe with Google Calendar",
        "Open/download JSON",
      ]);
    });

    // The disclosure is only a disclosure if it reaches everyone. role="menu"
    // accepts menuitem/group/separator children and assistive technology
    // skips the rest, so a note placed inside the menu is visible to
    // sighted users and dropped for the people most dependent on being told
    // where a link points.
    describe("the disclosure reaches assistive technology", () => {
      it("keeps the note out of the role=menu subtree", () => {
        const el = createElement({ "feed-json": JSON_URL });
        document.body.append(el);
        trigger(el).click();

        expect(el.shadowRoot!.querySelector(".menu-note")).not.toBeNull();
        expect(el.shadowRoot!.querySelector('[role="menu"] .menu-note')).toBeNull();
      });

      it("admits only permitted children into role=menu", () => {
        const el = createElement({ "feed-json": JSON_URL });
        document.body.append(el);
        trigger(el).click();

        const roles = Array.from(el.shadowRoot!.querySelectorAll('[role="menu"] > *')).map((node) =>
          node.getAttribute("role"),
        );
        expect(roles).toEqual(["group", "group", "group"]);
        for (const section of el.shadowRoot!.querySelectorAll('[role="group"]')) {
          // The visible heading is hidden from AT and its text given to the
          // group, which is the part a screen reader announces.
          expect(section.getAttribute("aria-label")).toBeTruthy();
          expect(section.querySelector(".menu-group-label")!.getAttribute("aria-hidden")).toBe("true");
          const itemRoles = Array.from(section.children)
            .filter((node) => !node.hasAttribute("aria-hidden"))
            .map((node) => node.getAttribute("role"));
          expect(new Set(itemRoles)).toEqual(new Set(["menuitem"]));
        }
      });

      it("says it in the trigger's accessible name, before the popover is opened", () => {
        const menu = createElement({ "feed-json": JSON_URL, name: "CoruñaJUG" });
        const badges = createElement({ "feed-json": JSON_URL, layout: "badges" });
        document.body.append(menu, badges);

        expect(trigger(menu).getAttribute("aria-label")).toBe(
          "Subscribe to CoruñaJUG (Generated from the OTE feed by the OTE converter.)",
        );
        expect(badge(badges, "rss").getAttribute("aria-label")).toBe("RSS (generated)");
        expect(badge(badges, "ote").getAttribute("aria-label")).toBe("OTE feed");
      });

      it("leaves the accessible name alone when nothing was generated", () => {
        const el = createElement({ "feed-ics": ICS_URL, "feed-rss": RSS_URL, name: "CoruñaJUG" });
        document.body.append(el);
        expect(trigger(el).getAttribute("aria-label")).toBe("Subscribe to CoruñaJUG");
      });
    });
  });

});
