const ICS_TOKENS: readonly ShowToken[] = ["google", "webcal", "ics-download"];
const RSS_TOKENS: readonly ShowToken[] = ["feedly", "feed-protocol", "rss-download"];
const OTE_TOKENS: readonly ShowToken[] = ["ote-reader", "ote-preview", "json-download"];

export interface SubscribeState {
  icsUrl: string | undefined;
  rssUrl: string | undefined;
  jsonUrl: string | undefined;
  name: string | undefined;
  show: Set<ShowToken>;
  /** Which formats may be generated by the conversion service when the publisher declared no URL for them. Empty disables it entirely. */
  convert: Set<ConvertToken>;
  lang: Lang;
  layout: SubscribeLayout;
  /** `"menu"` (the single combined trigger) or a GroupKey, whichever popover is currently open; null when none is. */
  openGroup: string | null;
  /** Stable across re-renders of the same element instance, for aria-controls. */
  instanceId: string;
  onToggle: (group: string) => void;
}

/** A format's URL and where it came from: the publisher's own attribute, or the conversion service standing in for a missing one (#186). */
interface ResolvedFeedUrl {
  url: string;
  generated: boolean;
}

/**
 * The publisher's own URL always wins; the service is a fallback for a
 * missing URL, never an override of a published one. Generation needs three
 * things to be true at once — the format is allowed by `convert`, there is a
 * JSON feed to convert, and that feed URL is one the service could actually
 * fetch (`isConvertibleFeedUrl`).
 */
function resolveFeedUrl(
  declared: string | undefined,
  jsonUrl: string | undefined,
  format: ConvertToken,
  convert: Set<ConvertToken>,
  build: (jsonUrl: string) => string,
): ResolvedFeedUrl | undefined {
  if (declared) return { url: declared, generated: false };
  if (!jsonUrl || !convert.has(format) || !isConvertibleFeedUrl(jsonUrl)) return undefined;
  return { url: build(jsonUrl), generated: true };
}

function buildGroups(state: SubscribeState, strings: (typeof STRINGS)[Lang]): RenderGroup[] {
  const groups: RenderGroup[] = [];
  const ics = resolveFeedUrl(state.icsUrl, state.jsonUrl, "ics", state.convert, buildConvertIcsUrl);
  const rss = resolveFeedUrl(state.rssUrl, state.jsonUrl, "rss", state.convert, buildConvertRssUrl);

  if (ics && ICS_TOKENS.some((token) => state.show.has(token))) {
    const items: RenderItem[] = [];
    if (state.show.has("google")) items.push({ label: strings.google, href: buildGoogleCalendarUrl(ics.url), external: true });
    if (state.show.has("webcal")) items.push({ label: strings.webcal, href: toWebcalUrl(ics.url), external: false });
    if (state.show.has("ics-download")) items.push({ label: strings.icsDownload, href: ics.url, external: true });
    if (items.length > 0) groups.push({ key: "ics", label: strings.calendarGroup, items, generated: ics.generated });
  }

  if (rss && RSS_TOKENS.some((token) => state.show.has(token))) {
    const items: RenderItem[] = [];
    if (state.show.has("feedly")) items.push({ label: strings.feedly, href: buildFeedlyUrl(rss.url), external: true });
    if (state.show.has("feed-protocol")) items.push({ label: strings.feedProtocol, href: toFeedProtocolUrl(rss.url), external: false });
    if (state.show.has("rss-download")) items.push({ label: strings.rssDownload, href: rss.url, external: true });
    if (items.length > 0) groups.push({ key: "rss", label: strings.rssGroup, items, generated: rss.generated });
  }

  if (state.jsonUrl && OTE_TOKENS.some((token) => state.show.has(token))) {
    const items: RenderItem[] = [];
    if (state.show.has("ote-reader")) items.push({ label: strings.oteReader, href: buildOteReaderUrl(state.jsonUrl), external: true });
    if (state.show.has("ote-preview")) items.push({ label: strings.otePreview, href: buildOtePreviewUrl(state.jsonUrl), external: true });
    if (state.show.has("json-download")) items.push({ label: strings.jsonDownload, href: state.jsonUrl, external: true });
    if (items.length > 0) groups.push({ key: "ote", label: strings.oteGroup, items, generated: false });
  }

  return groups;
}

function menuLink(item: RenderItem): HTMLAnchorElement {
  const a = withText(el("a"), item.label);
  a.href = item.href;
  a.setAttribute("role", "menuitem");
  if (item.external) {
    a.target = "_blank";
    a.rel = "noopener noreferrer";
  }
  return a;
}

/**
 * The "this came from the converter, not from the publisher" disclosure
 * (#186). Honest about the third party a visitor is about to subscribe to,
 * and it doubles as advertising for the escape hatch. Rendered once per
 * popover: in `layout="badges"` a popover holds one group, and in
 * `layout="menu"` the generated groups are marked in their own labels.
 *
 * Plain text with no role, matching `.menu-group-label`: an interactive
 * element inside `role="menu"` that is not a `menuitem` would break the
 * menu's accessibility contract, so the converter is named rather than
 * linked.
 */
function generatedNote(strings: (typeof STRINGS)[Lang]): HTMLElement {
  return withText(el("div", "menu-note"), strings.generatedNote);
}

/**
 * The popover box: a `role="menu"` plus, when there is one, the generated
 * note **outside** it.
 *
 * The note cannot live inside the menu. `role="menu"` accepts only
 * `menuitem`/`menuitemcheckbox`/`menuitemradio`/`group`/`separator`
 * children, and assistive technology in menu mode routinely skips anything
 * else — so a disclosure placed in there is visible to sighted users and
 * silently dropped for everyone else, which is the opposite of disclosing
 * it. The trigger's accessible name carries it as well, for the same
 * reason: that is the only part a screen-reader user hears before deciding
 * to open the thing.
 */
function buildPopover(menuId: string, group: RenderGroup, strings: (typeof STRINGS)[Lang]): HTMLElement {
  const popover = el("div", "popover");
  const menu = el("div", "menu");
  menu.id = menuId;
  menu.setAttribute("role", "menu");
  menu.append(...group.items.map(menuLink));
  popover.append(menu);
  if (group.generated) popover.append(generatedNote(strings));
  return popover;
}

/** One trigger + its popover (when open), wrapped in its own positioning context so the menu anchors under that specific trigger. */
function renderTrigger(
  container: HTMLElement,
  options: {
    groupKey: string;
    slotName: string;
    fallbackLabel: string;
    ariaLabel: string;
    disabled: boolean;
    open: boolean;
    menuId: string;
    iconSvg?: string;
    /** Marks a trigger whose URLs the conversion service generated, as a styling/test hook. Not an aria concern: the disclosure lives in the popover text. */
    generated?: boolean;
    buildMenuContent: () => HTMLElement;
    onClick: () => void;
  },
): void {
  const wrap = el("div", "item");
  const trigger = el("button", "trigger");
  trigger.type = "button";
  trigger.dataset.group = options.groupKey;
  trigger.disabled = options.disabled;
  trigger.setAttribute("aria-haspopup", "menu");
  trigger.setAttribute("aria-expanded", String(options.open));
  trigger.setAttribute("aria-label", options.ariaLabel);
  if (options.generated) trigger.dataset.generated = "";

  if (options.iconSvg) {
    const icon = el("span", "icon");
    icon.innerHTML = options.iconSvg;
    trigger.append(icon);
  }

  const slot = document.createElement("slot");
  slot.name = options.slotName;
  slot.textContent = options.fallbackLabel;
  trigger.append(slot);

  trigger.addEventListener("click", () => {
    if (!options.disabled) options.onClick();
  });
  wrap.append(trigger);

  if (options.open && !options.disabled) {
    trigger.setAttribute("aria-controls", options.menuId);
    wrap.append(options.buildMenuContent());
  }

  container.append(wrap);
}

export function renderSubscribe(container: HTMLElement, state: SubscribeState): void {
  container.replaceChildren();
  const strings = STRINGS[state.lang];
  const groups = buildGroups(state, strings);
  const baseAriaLabel = state.name ? strings.subscribeTo(state.name) : strings.subscribe;
  const ariaLabel = groups.some((group) => group.generated)
    ? `${baseAriaLabel} (${strings.generatedNote})`
    : baseAriaLabel;

  if (groups.length === 0) {
    renderTrigger(container, {
      groupKey: "menu",
      slotName: "trigger",
      fallbackLabel: strings.subscribe,
      ariaLabel,
      disabled: true,
      open: false,
      menuId: "",
      buildMenuContent: () => el("div", "menu"),
      onClick: () => {},
    });
    return;
  }

  if (state.layout === "badges") {
    const badgeLabel: Record<GroupKey, string> = {
      ics: strings.icsBadge,
      rss: strings.rssBadge,
      ote: strings.oteBadge,
    };
    for (const group of groups) {
      renderTrigger(container, {
        groupKey: group.key,
        slotName: `${group.key}-trigger`,
        fallbackLabel: badgeLabel[group.key],
        ariaLabel: group.generated ? `${group.label} (${strings.generatedTag})` : group.label,
        disabled: false,
        open: state.openGroup === group.key,
        menuId: `menu-${state.instanceId}-${group.key}`,
        iconSvg: ICONS[group.key],
        generated: group.generated,
        buildMenuContent: () => buildPopover(`menu-${state.instanceId}-${group.key}`, group, strings),
        onClick: () => state.onToggle(group.key),
      });
    }
    return;
  }

  renderTrigger(container, {
    groupKey: "menu",
    slotName: "trigger",
    fallbackLabel: strings.subscribe,
    ariaLabel,
    disabled: false,
    open: state.openGroup === "menu",
    menuId: `menu-${state.instanceId}`,
    generated: groups.some((group) => group.generated),
    buildMenuContent: () => {
      const popover = el("div", "popover");
      const menu = el("div", "menu");
      menu.id = `menu-${state.instanceId}`;
      menu.setAttribute("role", "menu");
      // One note for the whole popover, not one per generated group: the
      // common case (a JSON-only publisher) generates both Calendar and
      // RSS, and the same sentence twice in one menu reads as a glitch.
      // Which groups it refers to is carried by their labels instead.
      for (const group of groups) {
        const label = group.generated ? `${group.label} · ${strings.generatedTag}` : group.label;
        // role="group" with an accessible name is what makes the section
        // heading reach assistive technology: a bare <div> inside
        // role="menu" is not a permitted child and gets skipped, so the
        // visible label is aria-hidden and its text is given to the group.
        const section = el("div", "menu-section");
        section.setAttribute("role", "group");
        section.setAttribute("aria-label", label);
        const heading = withText(el("div", "menu-group-label"), label);
        heading.setAttribute("aria-hidden", "true");
        section.append(heading, ...group.items.map(menuLink));
        menu.append(section);
      }
      popover.append(menu);
      if (groups.some((group) => group.generated)) popover.append(generatedNote(strings));
      return popover;
    },
    onClick: () => state.onToggle("menu"),
  });
}
