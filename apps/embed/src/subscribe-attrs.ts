export type ShowToken =
  | "google"
  | "webcal"
  | "ics-download"
  | "feedly"
  | "feed-protocol"
  | "rss-download"
  | "ote-reader"
  | "ote-preview"
  | "json-download";

export const ALL_SHOW_TOKENS: readonly ShowToken[] = [
  "google",
  "webcal",
  "ics-download",
  "feedly",
  "feed-protocol",
  "rss-download",
  "ote-reader",
  "ote-preview",
  "json-download",
];

function isShowToken(value: string): value is ShowToken {
  return (ALL_SHOW_TOKENS as readonly string[]).includes(value);
}

export type SubscribeLayout = "menu" | "badges";

/**
 * "menu" (default): one trigger, one popover listing every available group
 * with a section label. "badges": one small trigger per available group
 * (Calendar/RSS/OTE feed), each with its own popover — the ComBuilders
 * three-badge layout this element was ported from.
 */
export function parseSubscribeLayout(value: string | null): SubscribeLayout {
  return value === "badges" ? "badges" : "menu";
}

/**
 * Comma-separated allow-list of which subscribe links to render, same
 * full-replacement semantics as attrs.ts's parseFields/parseEventActions:
 * absent/empty/all-unrecognized falls back to every token, `show="none"`
 * yields an empty set, any other valid input fully replaces the default.
 *
 * This does not know which of `feed-ics`/`feed-rss` are actually set —
 * subscribe-render.ts intersects the result with whichever feed URLs are
 * present, the same separation `parseFields`'s FieldKeys have from whether
 * an event actually has that data.
 */
export function parseShow(value: string | null): Set<ShowToken> {
  if (value === "none") return new Set();
  if (!value) return new Set(ALL_SHOW_TOKENS);
  const requested = value
    .split(",")
    .map((token) => token.trim())
    .filter(isShowToken);
  return requested.length > 0 ? new Set(requested) : new Set(ALL_SHOW_TOKENS);
}

export type ConvertToken = "ics" | "rss";

export const ALL_CONVERT_TOKENS: readonly ConvertToken[] = ["ics", "rss"];

function isConvertToken(value: string): value is ConvertToken {
  return (ALL_CONVERT_TOKENS as readonly string[]).includes(value);
}

/**
 * Which formats may be generated by convert.opentechevents.org when the
 * publisher has not declared their own URL for them (#186).
 *
 * Default-on, because that is the whole point: every entry in the public
 * adopters registry publishes JSON and nothing else, so an unmodified
 * `<ote-subscribe feed-json="…">` gains working calendar and reader links
 * with no edit. Default-off would make the capability something each
 * adopter has to discover.
 *
 * **It fails closed, which is where it diverges from `parseShow`.** `show`
 * and `fields` treat an all-unrecognized value as "the author typed
 * something meaningless, give them the default" — right for an attribute
 * whose default is a richer UI, and wrong for one whose job is to stop
 * third-party URLs from being built. `off` and `none` are spelled out, but
 * so is every other way a host tries to say no: an adversarial reading of
 * the first draft found `convert="false"`, `"no"`, `"0"` and `"disabled"`
 * all falling through to "generate everything", which is the worst possible
 * answer to someone who was clearly opting out. So any non-empty value that
 * names no format at all disables generation. Only an absent or empty
 * attribute means the default — a host who wrote nothing expressed no
 * opinion, and a framework binding that renders `convert=""` for "no value"
 * is the same case.
 */
export function parseConvert(value: string | null): Set<ConvertToken> {
  const normalized = value?.trim().toLowerCase();
  if (normalized === undefined || normalized === "") return new Set(ALL_CONVERT_TOKENS);
  const requested = normalized
    .split(",")
    .map((token) => token.trim())
    .filter(isConvertToken);
  return new Set(requested);
}
